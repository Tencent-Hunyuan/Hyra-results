"""Generate degree-p Cartesian treecode Triton kernels (P2M all levels, M2L, L2P all levels).

Conventions (moments WITHOUT factorials):
  M_B^b   = sum_{j in B} q_j (x_j - c_B)^b
  b_g(R)  = D^g(1/|R|)/g!,  recursion  |g| R^2 b_g = -[(2|g|-1) sum_i R_i b_{g-e_i} + (|g|-1) sum_i b_{g-2e_i}]
  1/|R + a - b| = sum_{|a|+|b|<=p} C(a+b,a) (-1)^|b| b_{a+b}(R) a^a b^b        (two-sided, symmetric)
  L_A^a  += sum_b C(a+b,a) (-1)^|b| b_{a+b}(c_A - c_B) M_B^b,   phi_far(x) = sum_{A ancestors} sum_a L_A^a (x-c_A)^a
"""
from __future__ import annotations

import importlib.util
import math
import os
import tempfile
from pathlib import Path

_cache_override = os.environ.get("HYFF_LR_CACHE_DIR")
_inductor_cache = os.environ.get("TORCHINDUCTOR_CACHE_DIR")
if _cache_override:
    GEN_DIR = Path(_cache_override)
elif _inductor_cache:
    GEN_DIR = Path(_inductor_cache) / "hyff_long_range_codegen"
else:
    GEN_DIR = Path.home() / ".cache/hyff/long_range_codegen"


def multi_indices(p):
    return [(i, j, n - i - j) for n in range(p + 1) for i in range(n, -1, -1) for j in range(n - i, -1, -1)]


def name(prefix, a):
    return f"{prefix}{a[0]}_{a[1]}_{a[2]}"


def multinomial_binom(a, b):
    return math.prod(math.comb(x + y, x) for x, y in zip(a, b))


def m2l_terms(p):
    """(alpha, beta, gamma=alpha+beta, coefficient) for |alpha|+|beta|<=p."""
    mi = multi_indices(p)
    out = []
    for b in mi:
        for a in mi:
            if sum(a) + sum(b) <= p:
                g = tuple(x + y for x, y in zip(a, b))
                out.append((a, b, g, multinomial_binom(a, b) * (-1) ** sum(b)))
    return out


def _monomials(lines, mi, pre, base, ax, indent):
    """m^a = base * prod(axes); m_0 = base. Each from a lower monomial by one factor."""
    ind = " " * indent
    lines.append(f"{ind}{name(pre, (0, 0, 0))} = {base}")
    for a in mi[1:]:
        k = next(i for i in range(3) if a[i])
        lo = list(a)
        lo[k] -= 1
        lines.append(f"{ind}{name(pre, a)} = {name(pre, tuple(lo))} * {ax[k]}")


def _taylor(lines, mi, indent):
    ind = " " * indent
    lines.append(f"{ind}inv_r2 = 1.0 / (rx * rx + ry * ry + rz * rz)")
    lines.append(f"{ind}{name('b', (0, 0, 0))} = tl.sqrt(inv_r2)")
    rr = ("rx", "ry", "rz")
    for g in mi[1:]:
        n = sum(g)
        t1 = []
        for i in range(3):
            if g[i] >= 1:
                lo = list(g)
                lo[i] -= 1
                t1.append(f"{rr[i]} * {name('b', tuple(lo))}")
        t2 = []
        for i in range(3):
            if g[i] >= 2:
                lo = list(g)
                lo[i] -= 2
                t2.append(name('b', tuple(lo)))
        expr = f"{float(2 * n - 1)!r} * ({' + '.join(t1)})"
        if t2 and n > 1:
            expr += f" + {float(n - 1)!r} * ({' + '.join(t2)})"
        lines.append(f"{ind}{name('b', g)} = ({expr}) * (inv_r2 * {-1.0 / n!r})")


def generate(p):
    mi = multi_indices(p)
    nm = len(mi)
    idx = {a: i for i, a in enumerate(mi)}
    L = ["# AUTO-GENERATED by hyff.kernels.long_range.codegen; do not edit.", "import triton", "import triton.language as tl",
         f"P = {p}", f"NM = {nm}", ""]
    # ---- P2M at every level: PART[(lev*NL + leaf)*NM + a] = sum_i q_i (x_i - c_anc)^a
    L += ["@triton.jit",
          "def p2m_kernel(XS, QS, CEN, PART, L, D, B: tl.constexpr):",
          "    leaf = tl.program_id(0)",
          "    s = leaf * B + tl.arange(0, B)",
          "    x = tl.load(XS + 3 * s)", "    y = tl.load(XS + 3 * s + 1)", "    z = tl.load(XS + 3 * s + 2)",
          "    q = tl.load(QS + s)",
          "    for lev in range(0, D + 1):",
          "        anc = (L >> lev) + (leaf >> lev)",
          "        ax = x - tl.load(CEN + 3 * anc)", "        ay = y - tl.load(CEN + 3 * anc + 1)",
          "        az = z - tl.load(CEN + 3 * anc + 2)"]
    _monomials(L, mi, "m", "q", ("ax", "ay", "az"), 8)
    L.append(f"        base = PART + (lev * L + leaf) * {nm}")
    for a in mi:
        L.append(f"        tl.store(base + {idx[a]}, tl.sum({name('m', a)}, 0))")
    L.append("")
    # ---- M2L over directed far CSR (target heap node owns its row).
    L += ["@triton.jit",
          "def m2l_kernel(CEN, MOM, ROWPTR, COLS, LOC, BLOCK: tl.constexpr):",
          "    t = tl.program_id(0)",
          "    start = tl.load(ROWPTR + t)", "    end = tl.load(ROWPTR + t + 1)",
          "    cx = tl.load(CEN + 3 * t)", "    cy = tl.load(CEN + 3 * t + 1)", "    cz = tl.load(CEN + 3 * t + 2)"]
    for a in mi:
        L.append(f"    {name('acc', a)} = tl.zeros((BLOCK,), tl.float32)")
    L += ["    for e0 in range(start, end, BLOCK):",
          "        e = e0 + tl.arange(0, BLOCK)",
          "        msk = e < end",
          "        src = tl.load(COLS + e, mask=msk, other=0)",
          "        rx = tl.where(msk, cx - tl.load(CEN + 3 * src, mask=msk, other=0.0), 1.0e4)",
          "        ry = tl.where(msk, cy - tl.load(CEN + 3 * src + 1, mask=msk, other=0.0), 0.0)",
          "        rz = tl.where(msk, cz - tl.load(CEN + 3 * src + 2, mask=msk, other=0.0), 0.0)"]
    _taylor(L, mi, 8)
    terms = m2l_terms(p)
    for b in mi:
        L.append(f"        mb = tl.load(MOM + src * {nm} + {idx[b]}, mask=msk, other=0.0)")
        for (a, bb, g, c) in terms:
            if bb != b:
                continue
            L.append(f"        {name('acc', a)} += ({float(c)!r} * {name('b', g)}) * mb")
    L.append(f"    base = LOC + t * {nm}")
    for a in mi:
        L.append(f"    tl.store(base + {idx[a]}, tl.sum({name('acc', a)}, 0))")
    L.append("")
    # ---- L2P from every ancestor: phi = sum L^a m^a, g = grad.
    L += ["@triton.jit",
          "def l2p_kernel(XS, CEN, LOC, PHI, G, L, D, B: tl.constexpr):",
          "    leaf = tl.program_id(0)",
          "    s = leaf * B + tl.arange(0, B)",
          "    x = tl.load(XS + 3 * s)", "    y = tl.load(XS + 3 * s + 1)", "    z = tl.load(XS + 3 * s + 2)",
          "    phi = tl.zeros((B,), tl.float32)", "    gx = tl.zeros((B,), tl.float32)",
          "    gy = tl.zeros((B,), tl.float32)", "    gz = tl.zeros((B,), tl.float32)",
          "    one = tl.full((B,), 1.0, tl.float32)",
          "    for lev in range(0, D + 1):",
          "        anc = (L >> lev) + (leaf >> lev)",
          "        ax = x - tl.load(CEN + 3 * anc)", "        ay = y - tl.load(CEN + 3 * anc + 1)",
          "        az = z - tl.load(CEN + 3 * anc + 2)",
          f"        base = LOC + anc * {nm}"]
    _monomials(L, mi, "m", "one", ("ax", "ay", "az"), 8)
    for a in mi:
        L.append(f"        la = tl.load(base + {idx[a]})")
        L.append(f"        phi += la * {name('m', a)}")
        for k, gname in enumerate(("gx", "gy", "gz")):
            if a[k]:
                lo = list(a)
                lo[k] -= 1
                L.append(f"        {gname} += (la * {float(a[k])!r}) * {name('m', tuple(lo))}")
    L += ["    tl.store(PHI + s, phi)", "    tl.store(G + 3 * s, gx)", "    tl.store(G + 3 * s + 1, gy)",
          "    tl.store(G + 3 * s + 2, gz)", ""]
    return "\n".join(L)


_CACHE = {}


def load(p):
    """Import (generating if absent or stale) the kernel module for degree p."""
    if p in _CACHE:
        return _CACHE[p]
    GEN_DIR.mkdir(parents=True, exist_ok=True)
    path = GEN_DIR / f"lq_gen_p{p}.py"
    src = generate(p)
    if not path.exists() or path.read_text() != src:
        tmp = None
        try:
            with tempfile.NamedTemporaryFile(mode="wb", dir=GEN_DIR,
                    prefix=f".lq_gen_p{p}.", suffix=".tmp", delete=False) as stream:
                tmp = Path(stream.name)
                stream.write(src.encode("utf-8"))
            tmp.replace(path)
        finally:
            if tmp is not None:
                tmp.unlink(missing_ok=True)
    spec = importlib.util.spec_from_file_location(f"lq_gen_p{p}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    _CACHE[p] = mod
    return mod
