"""Initialize project homes and spawn detached worker-loop processes.

Layouts come from execution.layout; model selection comes from hyprover.codex.
Worker MCP configuration uses the current Python interpreter to run the installed
gateway module and is refreshed on loop startup. Initialization and spawning are
separate operations: creating a project does not start research or publish facts.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional

from hyprover import codex

from . import layout as L

# --------------------------------------------------------------------------- #
# atomic file helpers                                                         #
# --------------------------------------------------------------------------- #

def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def _toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def symlink(target: Path, link: Path) -> None:
    """Create a link if absent; ignore OS errors without providing a copy fallback."""
    if link.is_symlink() or link.exists():
        return
    try:
        os.symlink(target, link)
    except OSError:
        pass


# --------------------------------------------------------------------------- #
# codex config template + task placeholder                                    #
# --------------------------------------------------------------------------- #

# The MCP server is the installed hyprover gateway (role=worker) launched as a
# module (see docs/ARCHITECTURE.md): `python -m hyprover.gateway` +
# HYPROVER_ROLE. `command` is the interpreter the worker loop itself runs on
# (sys.executable — the same Python hyprover was launched with), so the gateway can
# never resolve to a different `python3` on codex's PATH. It is rewritten every
# time the loop starts, so a moved/rebuilt venv is picked up automatically.
_CODEX_CONFIG = """\
# Auto-generated by hyprover (rewritten each time the worker loop starts); do not hand-edit.
[mcp_servers.hyprover]
command = {python}
args = ["-m", "hyprover.gateway"]
# fact_submit may wait for a long-running independent verifier.
# HYPROVER_MCP_TOOL_TIMEOUT controls this client limit; configure it alongside
# the separate HYPROVER_VERIFY_TIMEOUT HTTP limit to avoid premature cancellation.
tool_timeout_sec = {tool_timeout}

[mcp_servers.hyprover.env]
HYPROVER_PROJECT_DIR = {project_dir}
HYPROVER_AUTHOR = {author}
HYPROVER_ROLE = "worker"
HYPROVER_VERIFY_URL = {verify_url}
"""

_TASK_PLACEHOLDER = (
    "# Task\n\n(unassigned — the main agent writes your assignment here via "
    "`hyprover assign`; you read this file at the start of every round)\n"
)


def _verify_url() -> str:
    # each fact_submit POSTs here; the verify service spawns a fresh codex to
    # verify. Standard local endpoint by default; override with HYPROVER_VERIFY_URL.
    return os.environ.get("HYPROVER_VERIFY_URL", "http://127.0.0.1:8091/verify")


def _default_model() -> str:
    return codex.model("HYPROVER_WORKER_MODEL")


def write_codex_config(wl: "L.WorkerLayout") -> None:
    """Write the worker's ``.codex/config.toml``, pinning the gateway ``command``
    to THIS interpreter (``sys.executable``). Used at scaffold time and rewritten
    at every loop start (see ``loop.main``), so the worker's gateway always runs on
    the same Python as hyprover — never a bare ``python3`` that PATH could resolve to
    a different install (which would silently point the worker at another codebase
    / an incompatible ``mcp``)."""
    L.require_knowledge(wl.project_dir)
    tool_timeout = int(os.environ.get("HYPROVER_MCP_TOOL_TIMEOUT", "3600"))
    if tool_timeout <= 0:
        raise ValueError("MCP tool timeout must be positive")
    atomic_write(wl.codex_config, _CODEX_CONFIG.format(
        tool_timeout=tool_timeout,
        python=_toml_str(sys.executable),
        project_dir=_toml_str(str(wl.project_dir)),
        author=_toml_str(wl.name),
        verify_url=_toml_str(_verify_url()),
    ))


# --------------------------------------------------------------------------- #
# do_new — scaffold a project                                                 #
# --------------------------------------------------------------------------- #

def do_new(project: str, roles: str = L.DEFAULT_ROLES,
           model: Optional[str] = None) -> Dict:
    """Scaffold a project dir + one worker home per role. Refuses to clobber an
    existing project dir (no silent overwrite of a knowledge notebook). Returns
    ``{"project_dir", "workers"}``."""
    pdir = L.project_dir(project)
    if pdir.exists():
        raise SystemExit(f"project already exists: {pdir} (pick another name or remove it)")
    role_pairs = L.parse_roles(roles)
    model = model or _default_model()

    L.KnowledgeStore.initialize(pdir, problem_id=project)
    meta = {"name": project, "model": model, "roles": roles,
            "workers": [worker for worker, _ in role_pairs],
            "knowledge_format": L.KNOWLEDGE_FORMAT, "allow_math_computation": False}
    atomic_write(pdir / "project.json", json.dumps(meta, ensure_ascii=False, indent=2))
    L.require_knowledge(pdir)
    L.workers_dir(project).mkdir(parents=True, exist_ok=True)

    created: List[str] = []
    for worker, base in role_pairs:
        wl = L.WorkerLayout(L.worker_dir(project, worker))
        wl.local_memory.mkdir(parents=True, exist_ok=True)
        wl.logs.mkdir(exist_ok=True)

        # static contract (symlink stays in sync with the repo); there are no
        # worker skill files — worker.md is the whole procedure
        symlink(L.worker_md(), wl.dir / "AGENTS.md")

        # codex MCP wiring (role=worker)
        write_codex_config(wl)
        atomic_write(wl.task, _TASK_PLACEHOLDER)
        atomic_write(wl.role,
                     f"MODEL={model}\nREASONING_EFFORT={base}\nROLE={base}\nHYPROVER_AUTHOR={worker}\n")
        atomic_write(wl.status,
                     json.dumps({"worker": worker, "state": "created", "round": 0}, indent=2))
        created.append(worker)

    return {"project_dir": str(pdir), "workers": created}


# --------------------------------------------------------------------------- #
# spawn_loop — detached launch of one worker's outer loop                     #
# --------------------------------------------------------------------------- #

def spawn_loop(wdir: Path) -> int:
    """Launch ``python -m hyprover.execution <wdir>`` detached in its own process
    group (``start_new_session=True``) so ``hyprover stop --force`` can ``killpg``
    the loop *and* its in-flight codex child. Returns the child pid."""
    wl = L.WorkerLayout(wdir)
    L.require_knowledge(wl.project_dir)
    if not wl.dir.is_dir():
        raise SystemExit(f"no such worker: {wl.project}/{wl.name}")
    wl.logs.mkdir(parents=True, exist_ok=True)
    logf = open(wl.logs / "loop.log", "a", encoding="utf-8")
    try:
        proc = subprocess.Popen(
            [sys.executable, "-m", "hyprover.execution", str(wdir)],
            stdout=logf, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
            start_new_session=True,
        )
    finally:
        logf.close()
    return proc.pid
