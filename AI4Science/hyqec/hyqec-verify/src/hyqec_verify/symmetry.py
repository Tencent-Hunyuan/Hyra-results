"""Qubit-permutation automorphisms and orbits (candidates are never trusted).

A qubit permutation pi with pi(S) = S preserves N(S), S and Pauli weight, so it
maps minimum-weight logicals to minimum-weight logicals. Both lower-bound
engines use this only through *orbits* of the group generated by verified
permutations: some minimum-weight logical avoids every orbit before the first
one it meets and contains that orbit's representative (docs/SOUNDNESS.md).

Candidates come from block-cyclic shifts / multipliers (cheap, common for
quasi-cyclic constructions) and from nauty if ``pynauty`` is installed; each is
checked with ``StabilizerCode.is_automorphism`` before use.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from math import gcd
from typing import Sequence

from .core import CodeError, StabilizerCode

__all__ = ["Orbits", "orbits_from", "find_automorphisms", "trivial_orbits"]


@dataclass
class Orbits:
    orbit_of: list[int]          # orbit index of each qubit (orbits numbered in root order)
    reps: list[int]              # representative of each orbit
    generators: list[list[int]] = field(default_factory=list)   # verified permutations

    @property
    def count(self) -> int:
        return len(self.reps)

    def members(self) -> list[list[int]]:
        out = [[] for _ in self.reps]
        for q, o in enumerate(self.orbit_of):
            out[o].append(q)
        return out

    def to_json(self) -> dict:
        return {"generators": self.generators, "reps": self.reps, "orbit_of": self.orbit_of}


def trivial_orbits(n: int, order: Sequence[int] | None = None) -> Orbits:
    order = list(order) if order is not None else list(range(n))
    if sorted(order) != list(range(n)):
        raise ValueError("order must be a permutation of range(n)")
    orbit_of = [0] * n
    for i, q in enumerate(order):
        orbit_of[q] = i
    return Orbits(orbit_of, order, [])


def orbits_from(code: StabilizerCode, perms: Sequence[Sequence[int]], *,
                rep_order: Sequence[int] | None = None) -> Orbits:
    """Orbits of the group generated by ``perms``; every permutation is verified first.

    rep_order: optional qubit priority; orbits are numbered by their first qubit in it,
    and each representative is that first qubit (any choice is sound)."""
    n = code.n
    perms = [list(p) for p in perms]
    for i, p in enumerate(perms):
        if not code.is_automorphism(p):
            raise CodeError(f"permutation {i} is not an automorphism of the stabilizer group")
    parent = list(range(n))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    for p in perms:
        for q in range(n):
            a, b = find(q), find(p[q])
            if a != b:
                parent[max(a, b)] = min(a, b)
    order = list(rep_order) if rep_order is not None else list(range(n))
    if sorted(order) != list(range(n)):
        raise ValueError("rep_order must be a permutation of range(n)")
    idx: dict[int, int] = {}
    reps: list[int] = []
    for q in order:
        r = find(q)
        if r not in idx:
            idx[r] = len(reps)
            reps.append(q)
    return Orbits([idx[find(q)] for q in range(n)], reps, perms)


def _block_shift(n, P, step=1):
    return [(q // P) * P + ((q % P) + step) % P for q in range(n)]


def _block_mult(n, P, a):
    return [(q // P) * P + ((q % P) * a) % P for q in range(n)]


def block_cyclic_automorphisms(code: StabilizerCode, multipliers: bool = True) -> list[list[int]]:
    """Largest block size P (n % P == 0) whose simultaneous in-block rotation is an
    automorphism, plus in-block multipliers s -> a s (gcd(a, P) = 1) that are too."""
    n = code.n
    for P in sorted((p for p in range(2, n + 1) if n % p == 0), reverse=True):
        p = _block_shift(n, P)
        if code.is_automorphism(p):
            found = [p]
            if multipliers:
                for a in range(2, P):
                    if gcd(a, P) == 1:
                        pm = _block_mult(n, P, a)
                        if code.is_automorphism(pm):
                            found.append(pm)
            return found
    return []


def nauty_automorphisms(code: StabilizerCode) -> list[list[int]]:
    """Qubit permutations induced by automorphisms of the Pauli-labelled Tanner graph
    (pynauty, optional). Each is re-verified by the caller (orbits_from)."""
    try:
        import pynauty
    except ImportError:
        return []
    n = code.n
    gens = code.generators
    m = len(gens)
    adj: dict[int, list[int]] = {}
    nv = n + m
    sub = {1: [], 2: [], 3: []}
    for g, v in enumerate(gens):
        for q in range(n):
            lab = ((v >> q) & 1) | (((v >> (n + q)) & 1) << 1)
            if lab:
                adj.setdefault(nv, []).extend([q, n + g])
                sub[lab].append(nv)
                nv += 1
    coloring = [set(range(n)), set(range(n, n + m))] + [set(sub[l]) for l in (1, 2, 3) if sub[l]]
    G = pynauty.Graph(nv, directed=False, adjacency_dict=adj, vertex_coloring=coloring)
    gens_aut = pynauty.autgrp(G)[0]
    return [list(p[:n]) for p in gens_aut]


def find_automorphisms(code: StabilizerCode, method: str = "auto") -> list[list[int]]:
    """Verified automorphism candidates ("auto": nauty if available, else block-cyclic)."""
    if method in ("auto", "nauty"):
        perms = nauty_automorphisms(code)
        if perms or method == "nauty":
            return [p for p in perms if code.is_automorphism(p)]
    if method in ("auto", "cyclic"):
        return block_cyclic_automorphisms(code)
    if method == "none":
        return []
    raise ValueError(f"unknown automorphism method {method!r}")
